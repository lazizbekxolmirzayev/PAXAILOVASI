// Bundles the simulation engine (pure TypeScript, no DOM) into a single ESM file that the
// Supabase Edge Function imports — guaranteeing the server runs exactly the same rules as the client.
import { build } from 'esbuild';
await build({
  entryPoints: ['src/engine/server.ts'],
  bundle: true, format: 'esm', platform: 'neutral', target: 'es2022',
  outfile: 'supabase/functions/_shared/engine.js',
  banner: { js: '// AUTO-GENERATED by `npm run sync:engine` — do not edit.\n' },
  mainFields: ['module', 'main'],
});
console.log('Engine bundled → supabase/functions/_shared/engine.js');
