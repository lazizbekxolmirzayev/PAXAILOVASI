import { SCENARIOS } from '../data/scenarios';
import { narration, type Lang } from './script';

export const MANIFEST_LANGS: Lang[] = ['en', 'ru', 'uz'];
export type Manifest = Record<string, Record<Lang, string[]>>;

/** Everything the voice-over function may speak: built-in scenario id → language → one text per shot. */
export function buildManifest(): Manifest {
  const out: Manifest = {};
  for (const def of SCENARIOS) {
    out[def.id] = { en: [], ru: [], uz: [] };
    for (const lang of MANIFEST_LANGS) out[def.id][lang] = narration(def, lang);
  }
  return out;
}

/** Source text of api/_story-text.js (generated; see scripts/gen-story-text.ts). */
export function manifestModuleSource(): string {
  return `// AUTO-GENERATED by scripts/gen-story-text.ts — do not edit by hand. Regenerate with: npm run gen:story\n// The only texts /api/tts is allowed to turn into speech (scenario id -> language -> one text per shot).\nexport default ${JSON.stringify(buildManifest(), null, 1)};\n`;
}
