export function cityName(c: CityDef, year: number): string {
  for (const [until, name] of c.names) if (year < until) return name;
  return c.names[c.names.length - 1][1];
}
export function citiesForYear(year: number): CityDef[] {
  return CITIES.filter((c) => c.founded <= year && (c.abandoned === undefined || c.abandoned > year));
}
